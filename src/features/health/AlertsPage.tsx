import { CheckCircle2, Clock, HardDrive, type LucideIcon } from 'lucide-react';
import type { AlertSyncState } from '@/api/types';
import { DataState, PageHeader, StatusBadge } from '@/components/shared';
import { Card } from '@/components/ui/card';
import { formatTimestamp } from '@/lib/format';
import { statusOf } from '@/lib/queryState';
import { useAlerts, useAstronautContext } from './hooks';

const SYNC: Record<AlertSyncState, { label: string; icon: LucideIcon; className: string }> = {
  stored_locally: { label: 'Stored locally', icon: HardDrive, className: 'text-status-review' },
  pending: { label: 'Pending sync', icon: Clock, className: 'text-status-review' },
  synced: { label: 'Synced', icon: CheckCircle2, className: 'text-status-nominal' },
};

export function AlertsPage() {
  const { astronautId } = useAstronautContext();
  const alerts = useAlerts(astronautId);
  const items = alerts.data ?? [];

  return (
    <div className="space-y-6">
      <PageHeader
        title="Alerts"
        description="Generated by backend rules from your records. Each alert shows whether it has synced."
      />
      <DataState
        status={statusOf(alerts, items.length === 0)}
        error={alerts.error}
        onRetry={() => void alerts.refetch()}
        emptyMessage="No alerts."
      >
        <ul className="space-y-3">
          {items.map((a) => {
            const sync = SYNC[a.sync_state];
            const SyncIcon = sync.icon;
            return (
              <li key={a.alert_id}>
                <Card className="space-y-2 p-4" data-testid="alert">
                  <div className="flex flex-wrap items-center gap-2">
                    <StatusBadge status={a.severity} />
                    <h2 className="font-medium text-ink">{a.title}</h2>
                    <span
                      className={`ml-auto inline-flex items-center gap-1.5 text-label ${sync.className}`}
                    >
                      <SyncIcon className="h-3.5 w-3.5" aria-hidden="true" />
                      {sync.label}
                    </span>
                  </div>
                  <p className="text-sm text-ink-muted">{a.detail}</p>
                  <p className="text-caption text-ink-subtle">
                    {formatTimestamp(a.triggered_at)} · rule {a.rule_id} · source {a.source_table}
                  </p>
                </Card>
              </li>
            );
          })}
        </ul>
      </DataState>
    </div>
  );
}
